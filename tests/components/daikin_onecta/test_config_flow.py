    assert result["step_id"] == "oauth_discovery"

    result = await hass.config_entries.flow.async_configure(result["flow_id"], {})
    state = oauth_state(result)

    assert result["url"] == (
        f"{OAUTH2_AUTHORIZE}?response_type=code&client_id={TEST_CLIENT_ID}"
        "&redirect_uri=https://example.com/auth/external/callback"
        f"&state={state}"
        f"&scope=openid+onecta:basic.integration+offline_access"
    )

    client = await hass_client_no_auth()
    resp = await client.get(f"/auth/external/callback?code=abcd&state={state}")
    assert resp.status == HTTP_OK
    assert resp.headers["content-type"] == "text/html; charset=utf-8"

    aioclient_mock.post(
        OAUTH2_TOKEN,
        json={
            "refresh_token": "mock-refresh-token",
            "access_token": FAKE_ACCESS_TOKEN,
            "type": "Bearer",
            "expires_in": 60,
        },
    )

    await hass.async_block_till_done()
    assert result["type"] == "external"
    assert result["url"].startswith(OAUTH2_AUTHORIZE)

    with patch(
        "homeassistant.components.daikin_onecta.async_setup_entry", return_value=True
    ) as mock_setup:
        await hass.config_entries.flow.async_configure(
            result["flow_id"],
            {},
        )

    await hass.async_block_till_done()
    assert len(hass.config_entries.async_entries(DOMAIN)) == 1
    assert len(mock_setup.mock_calls) == 1


