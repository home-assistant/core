TEST_CLIENT_ID = "test-client-id"
TEST_CLIENT_SECRET = "test-client-secret"
HTTP_OK = 200
GATEWAY_DEVICES_URL = "https://api.onecta.daikineurope.com/v1/gateway-devices"


def oauth_state(result: dict[str, str]) -> str:
    """Return the state generated by the public OAuth flow response."""
    return parse_qs(urlparse(result["url"]).query)["state"][0]


@pytest.fixture(autouse=True)
async def setup_credentials(hass: HomeAssistant) -> None:
    """Fixture to setup credentials."""
    assert await async_setup_component(hass, "application_credentials", {})
    await async_import_client_credential(
        hass,
        DOMAIN,
        ClientCredential(TEST_CLIENT_ID, TEST_CLIENT_SECRET),
        DOMAIN,
    )


@pytest.mark.usefixtures("current_request_with_host")
async def test_full_flow(
    hass: HomeAssistant,
    hass_client_no_auth: ClientSessionGenerator,
    aioclient_mock: AiohttpClientMocker,
    setup_credentials,
) -> None:
    """Check full flow."""
    assert await async_setup_component(hass, "daikin_onecta", {})

    await async_import_client_credential(
        hass, DOMAIN, ClientCredential(TEST_CLIENT_ID, TEST_CLIENT_SECRET)
    )

    result = await hass.config_entries.flow.async_init(
        "daikin_onecta", context={"source": config_entries.SOURCE_USER}
    )
    state = oauth_state(result)

    assert result["url"] == (
        f"{OAUTH2_AUTHORIZE}?response_type=code&client_id={TEST_CLIENT_ID}"
        "&redirect_uri=https://example.com/auth/external/callback"
        f"&state={state}"
        f"&scope=openid+onecta:basic.integration+offline_access"
    )

    client = await hass_client_no_auth()
    resp = await client.get(f"/auth/external/callback?code=abcd&state={state}")
    assert resp.status == HTTP_OK
    assert resp.headers["content-type"] == "text/html; charset=utf-8"

    aioclient_mock.post(
        OAUTH2_TOKEN,
        json={
            "refresh_token": "mock-refresh-token",
            "access_token": FAKE_ACCESS_TOKEN,
            "type": "Bearer",
            "expires_in": 60,
        },
    )
    aioclient_mock.get(GATEWAY_DEVICES_URL, json=[])

    with patch(
        "homeassistant.components.daikin_onecta.async_setup_entry", return_value=None
    ) as mock_setup:
        await hass.config_entries.flow.async_configure(result["flow_id"])

    assert len(hass.config_entries.async_entries(DOMAIN)) == 1
    assert len(mock_setup.mock_calls) == 1
    entry = hass.config_entries.async_entries(DOMAIN)[0]
    assert entry.version == 1
    assert entry.minor_version == 1


