TEST_CLIENT_SECRET = "test-client-secret"
HTTP_OK = 200


def oauth_state(result: dict[str, str]) -> str:
    """Return the state generated by the public OAuth flow response."""
    return parse_qs(urlparse(result["url"]).query)["state"][0]


