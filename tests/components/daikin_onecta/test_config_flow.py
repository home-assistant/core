def oauth_state(result: ConfigFlowResult) -> str:
    """Return the state generated by the public OAuth flow response."""
    assert result["type"] is FlowResultType.EXTERNAL_STEP
    return parse_qs(urlparse(result["url"]).query)["state"][0]


async def _async_start_user_flow(hass: HomeAssistant) -> ConfigFlowResult:
    """Start the user OAuth flow."""
    return await hass.config_entries.flow.async_init(
        DOMAIN, context={"source": config_entries.SOURCE_USER}
    )


async def _async_start_zeroconf_flow(hass: HomeAssistant) -> ConfigFlowResult:
    """Start discovery and continue into the OAuth flow."""
    result = await hass.config_entries.flow.async_init(
        DOMAIN,
        context={"source": SOURCE_ZEROCONF},
        data=ZEROCONF_DISCOVERY,
    )
    assert result["type"] is FlowResultType.FORM
    assert result["step_id"] == "oauth_discovery"
    return await hass.config_entries.flow.async_configure(result["flow_id"], {})


async def _async_complete_user_flow(
    hass: HomeAssistant, flow_id: str
) -> ConfigFlowResult:
    """Complete the external callback in the user flow."""
    return await hass.config_entries.flow.async_configure(flow_id)


async def _async_complete_zeroconf_flow(
    hass: HomeAssistant, flow_id: str
) -> ConfigFlowResult:
    """Complete the external callback in the discovery flow."""
    await hass.async_block_till_done()
    return await hass.config_entries.flow.async_configure(flow_id, {})


async def async_reauth_external_step(
    hass: HomeAssistant,
    config_entry: MockConfigEntry,
    hass_client_no_auth: ClientSessionGenerator,
) -> ConfigFlowResult:
    """Start reauthentication through the flow manager and complete its callback."""
    result = await config_entry.start_reauth_flow(hass)
    assert result["type"] is FlowResultType.FORM
    result = await hass.config_entries.flow.async_configure(result["flow_id"], {})
    state = oauth_state(result)

    client = await hass_client_no_auth()
    response = await client.get(f"/auth/external/callback?code=abcd&state={state}")
    assert response.status == HTTP_OK
    return result


