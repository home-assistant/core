def box(kind: bytes, data: bytes = b"") -> bytes:
    """Create a finite MP4 box."""
    return struct.pack(">I4s", len(data) + 8, kind) + data


async def test_fragment_stream_and_prebuffer() -> None:
    """Retain complete fragments, ignoring auxiliary boxes."""
    reader = asyncio.StreamReader()
    reader.feed_data(
        box(b"ftyp")
        + box(b"free")
        + box(b"moov")
        + box(b"styp")
        + box(b"sidx")
        + box(b"moof", b"a")
        + box(b"mdat", b"b")
        + box(b"mfra")
    )
    reader.feed_eof()
    buffer = FragmentBuffer(4, 200)
    await read_fragments(reader, buffer)
    initialization, fragments = buffer.snapshot()
    assert initialization == box(b"ftyp") + box(b"free") + box(b"moov")
    assert fragments == (box(b"moof", b"a") + box(b"mdat", b"b"),)


async def test_rejects_oversized_box() -> None:
    """Reject an untrusted box before allocating its payload."""
    reader = asyncio.StreamReader()
    reader.feed_data(struct.pack(">I4s", 200, b"mdat"))
