async def test_native_remux_fragments_start_with_idr() -> None:
    """Real FFmpeg remux emits independently decodable short IDR fragments."""
    ffmpeg = shutil.which("ffmpeg")
    if ffmpeg is None:
        pytest.skip("FFmpeg is not installed")
    producer = await asyncio.create_subprocess_exec(
        ffmpeg,
        "-v",
        "error",
        "-f",
        "lavfi",
        "-i",
        "testsrc=size=320x240:rate=15",
        "-t",
        "6",
        "-c:v",
        "libx264",
        "-pix_fmt",
        "yuv420p",
        "-g",
        "30",
        "-keyint_min",
        "30",
        "-sc_threshold",
        "0",
        "-movflags",
        "frag_keyframe+empty_moov+default_base_moof",
        "-f",
        "mp4",
        "pipe:1",
        stdout=asyncio.subprocess.PIPE,
        stderr=asyncio.subprocess.PIPE,
    )
    source, error = await producer.communicate()
    assert producer.returncode == 0, error.decode()
    config = RecordingConfiguration(
        4000, 1, 4000, 2, 2, 1600, 4000, 1920, 1080, 15, 0, 1, 0, 1, 32
    )
    command = ffmpeg_command(ffmpeg, ["-i", "pipe:0"], config, False, copy_video=True)
    assert "-min_frag_duration" not in command
    remux = await asyncio.create_subprocess_exec(
        *command,
        stdin=asyncio.subprocess.PIPE,
        stdout=asyncio.subprocess.PIPE,
        stderr=asyncio.subprocess.PIPE,
    )
    output, error = await remux.communicate(source)
    assert remux.returncode == 0, error.decode()
    reader = asyncio.StreamReader()
    reader.feed_data(output)
    reader.feed_eof()
    buffer = FragmentBuffer(30, 10_000_000)
    await read_fragments(reader, buffer)
    initialization, fragments = buffer.snapshot()
    assert len(fragments) == 3
    for fragment in fragments:
        with av.open(BytesIO(initialization + fragment), format="mp4") as container:
            video = container.streams.video[0]
            extra = video.codec_context.extradata
            packets = [
                packet for packet in container.demux(video) if packet.dts is not None
            ]
            assert packets[0].is_keyframe
            assert _has_h264_idr(bytes(packets[0]), (extra[4] & 3) + 1)
            assert float((packets[-1].dts - packets[0].dts) * packets[0].time_base) <= 4
            assert sum(len(packet.decode()) for packet in packets) > 0
