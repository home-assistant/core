def box(kind: bytes, data: bytes = b"") -> bytes:
    """Create a finite MP4 box."""
    return struct.pack(">I4s", len(data) + 8, kind) + data


async def test_fragment_stream_and_prebuffer() -> None:
    """Retain complete fragments, ignoring auxiliary boxes."""
    reader = asyncio.StreamReader()
    reader.feed_data(
        box(b"ftyp")
        + box(b"free")
        + box(b"moov")
        + box(b"styp")
        + box(b"sidx")
        + box(b"moof", b"a")
        + box(b"mdat", b"b")
        + box(b"mfra")
    )
    reader.feed_eof()
    buffer = FragmentBuffer(4, 200)
    await read_fragments(reader, buffer)
    initialization, fragments = buffer.snapshot()
    assert initialization == box(b"ftyp") + box(b"free") + box(b"moov")
    assert fragments == (box(b"moof", b"a") + box(b"mdat", b"b"),)


async def test_rejects_oversized_box() -> None:
    """Reject an untrusted box before allocating its payload."""
    reader = asyncio.StreamReader()
    reader.feed_data(struct.pack(">I4s", 200, b"mdat"))
    with pytest.raises(ValueError):
        await read_box(reader, 100)


def test_boundaries_and_reconfiguration() -> None:
    """Evict entire fragments and clear them when initialization changes."""
    buffer = FragmentBuffer(4, 6)
    buffer.set_initialization(b"i")
    buffer.append(b"aa", 1)
    buffer.append(b"bbb", 2)
    buffer.append(b"cc", 3)
    assert buffer.snapshot(3) == (b"i", (b"bbb", b"cc"))
    assert buffer.snapshot(7) == (b"i", (b"cc",))
    buffer.set_initialization(b"new")
    assert buffer.snapshot(7) == (b"new", ())


async def test_ffmpeg_fragmented_mp4() -> None:
    """Read a finite fragmented MP4 generated by FFmpeg."""
    ffmpeg = shutil.which("ffmpeg")
    if ffmpeg is None:
        pytest.skip("FFmpeg is not installed")
    process = await asyncio.create_subprocess_exec(
        ffmpeg,
        "-v",
        "error",
        "-f",
        "lavfi",
        "-i",
        "testsrc=size=320x240:rate=15",
        "-t",
        "3",
        "-c:v",
        "libx264",
        "-g",
        "30",
        "-movflags",
        "frag_keyframe+empty_moov+default_base_moof",
        "-f",
        "mp4",
        "pipe:1",
        stdout=asyncio.subprocess.PIPE,
        stderr=asyncio.subprocess.PIPE,
    )
    assert process.stdout is not None
    buffer = FragmentBuffer(10, 5_000_000)
    try:
        await asyncio.wait_for(read_fragments(process.stdout, buffer), 20)
        assert await process.wait() == 0
        initialization, fragments = buffer.snapshot()
        assert b"ftyp" in initialization and b"moov" in initialization
        assert len(fragments) >= 1
        assert all(fragment[4:8] == b"moof" for fragment in fragments)
    finally:
        if process.returncode is None:
            process.kill()
            await process.wait()


